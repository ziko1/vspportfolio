// Функція для отримання перекладу за ключем
export const getTranslation = (locale, key, defaultValue = '') => {
  const keys = key.split('.')
  let value = translations[locale]
  
  for (const k of keys) {
    if (value && typeof value === 'object') {
      value = value[k]
    } else {
      return defaultValue
    }
  }
  
  return value !== undefined ? value : defaultValue
}

// Хук для використання перекладів (для React компонентів)
export const useTranslation = (locale) => {
  return {
    t: (key, defaultValue = '') => getTranslation(locale, key, defaultValue),
    locale
  }
}
